/**
 * mulberry32 — the sim's stream PRNG for future non-spatial randomness.
 * World generation itself uses the stateless spatial hash in noise.ts;
 * this exists so nothing ever reaches for Math.random.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 0x100000000;
  };
}
